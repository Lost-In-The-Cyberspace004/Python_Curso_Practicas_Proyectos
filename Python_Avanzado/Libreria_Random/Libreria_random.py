import random
print("Numero aleatorio: ", random.randrange(1, 100)) #NUMEROS ALEATORIOS DE 0 A 100
print("Lista aleatoria de numeros: ", random.sample(range(50), 6)) #LISTA DE NUMEROS ALEATORIOS, EL PRIMER PARAMETRO ES EL RANGO DE X NUMERO A X NUMERO Y EL 2DO PARAMETRO ES EL NUMERO DE NUMEROS GENERADOS EN LA LISTA
print("Numeros decimales aleatorios:", random.random())#Numeros aleatorios decimales
print("Eleccion aleatoria: ", random.choice(['rojo', 'azul', 'amarillo'])) #SELECCIONES ALEATORIAS


