#items: metodo que devuelve un objeto iterable compuesto por todos los elementos
#keys: metodo que devuelve todas las claves
#values: metodo que devuelve todos los valores que mantienen las claves

numeros = {
    "one": "uno",
    "two": "dos",
    "three": "tres"
}

print("diccionario: ", numeros)
print("diccionario: ", numeros.items())
print("diccionario: ", numeros.keys())
print("diccionario: ", numeros.values())