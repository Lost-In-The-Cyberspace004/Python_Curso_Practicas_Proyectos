import math
print("El valor absoluto de 7: ", math.fabs(-7)) #ENCONTRAR EL VALOR ABSOLUTO DE UN NUMERO
print("El factorial de 9 es: ", math.factorial(9))#ENCONTRAR EL FACTORIAL DE UN NUMERO
print("El maximo comun divisor de 39 y de 26 es: ", math.gcd(39, 26)) #MAXIMO COMUN DIVISOR
print("Verificar si es un numero: ", math.isnan(8)) #VERIFICAR SI ES UN NUMERO
print("El logaritmo base 10 de 540: ", math.log(540, 10)) #LOGARITMO BASE X DE CUALQUIER NUMERO
print("Exponentes: ", math.pow(2, 10)) #EXPONENTES
print("Raiz cuadrada de 144: ", math.sqrt(144)) #RAIZ CUADRADA

print("El ángulo 90 en radianes es: ", math.radians(90))
print("El ángulo 1.57 en grados es: ", math.degrees(1.57))
print("El seno de un ángulo de 180 es: ", math.sin(math.radians(180)))
print("El coseno de un ángulo de 180 es: ", math.cos(math.radians(180)))
print("La tangente de un ángulo de 180 es: ", math.tan(math.radians(180)))
print("El arcoseno de 1 es: ", math.degrees(math.asin(1)))
print("El arcocoseno de 1 es: ", math.degrees(math.acos(1)))
print("La arcotangente de 1 es: ", math.degrees(math.atan(1)))

print("El valor de pi es: ", math.pi)
print("El valor de e es: ", math.e)
print("El valor de tau es: ", math.tau)
print("El valor infinito es: ", math.inf)
print("El valor NaN es: ", math.nan)
