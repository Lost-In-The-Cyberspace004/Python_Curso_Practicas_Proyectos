'''
1-)    “r”: abre el fichero para lectura. Es el modo de apertura por defecto
        en el caso de que no se especifique uno.

2-)    “w”: abre el fichero para escritura truncándolo, es decir, borrando
        todo el contenido que tiene para empezar a escribir de nuevo desde
        cero.

3-)    “x”: crea un fichero para escribir en él. En caso de que ya exista
        devuelve un error.

4-)    “a”: abre el fichero para escritura situando el cursor de escritura al
        final del fichero.

5-)    “b”: abre el fichero en modo binario. Un fichero binario es un tipo de
        fichero con información representada en ceros y unos en lugar de
        texto plano, por ejemplo, fotografías, archivos ejecutables, ficheros
        de Microsoft Word, etc.

6-)    “t”: abre el fichero en modo fichero de texto. Es el modo de apertura
        por defecto en el caso de que no se especifique que sea binario o de
        texto.
    
7-)    “+”: abre el fichero para lectura y escritura.
'''